#!/usr/bin/env python3
"""Generate Gunk's Diamond follower tables from pret pokeheartgold's follower data.

usage: python3 -I tools/gunk/followers/gen_tables.py <pokeheartgold tree>

Reads (all pret code/data, nothing from Following Platinum):
  src/follow_mon.c                         sModelIndexLUT (species -> HG follower index),
                                           sFemaleFlagLUT, sFormMaxLUT (per species - 1)
  include/constants/follow_mon_idx.h       FOLLOWER_MON_* -> index (0..565)
  files/fielddata/tsurepoke/tp_param.csv   too_tall (64x64 sprite) per follower index

Writes (committed, so the build doesn't need the HG tree):
  arm9/asm/gunk_follower/*.inc one row per follower sprite for each overlay-5 map-object graphics table
                                           (included from arm9/asm/gunk_follower_tables.s, the arm9 copies of the tables)
  include/gunk/gunk_follower_species.h     species -> HG follower index, female flag, form count

Graphics ID of follower index n = 0x200 + n; its texture is mmodel member 415 + n (tools/gunk/followers/extract_hg.py),
the walk frame sequence is mmodel member 414 (frame-sequence index 21).
"""
import csv
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
FIRST_GFX = 0x200
FIRST_MEMBER = 415
FRAME_SEQ = 21
MODEL_32 = 0          # ov05_021F9094: model 0 = 32x32 billboard (mmodel 376)
MODEL_64 = 5          # model 5 = 64x64 billboard (mmodel 383)
DETAILS = 0x411       # billboard, shadow, no footprints, reflection (bitfields: type 4, shadow 2, track 4, refl 2)
COUNT = 566
SPECIES = 493


def lut(src, name):
    m = re.search(r'static const u16 %s\[\] = \{(.*?)\};' % name, src, re.S)
    assert m, name
    body = re.sub(r'//[^\n]*', '', m.group(1))
    return [v.strip() for v in body.split(',') if v.strip()]


def main():
    hg = sys.argv[1]
    src = open(os.path.join(hg, 'src/follow_mon.c')).read()
    idx = {}
    for line in open(os.path.join(hg, 'include/constants/follow_mon_idx.h')):
        m = re.match(r'#define (FOLLOWER_MON_\w+)\s+(\d+)', line)
        if m:
            idx[m.group(1)] = int(m.group(2))
    model_lut = [idx[v] if v.startswith('FOLLOWER_MON_') else int(v) for v in lut(src, 'sModelIndexLUT')]
    female = [1 if v == 'TRUE' else 0 for v in lut(src, 'sFemaleFlagLUT')]
    forms = [int(v) for v in lut(src, 'sFormMaxLUT')]
    assert len(model_lut) == SPECIES + 1 and len(female) == SPECIES and len(forms) == SPECIES
    names = [None] * COUNT
    for k, v in idx.items():
        if k != 'FOLLOWER_MON_NONE':
            names[v] = k[len('FOLLOWER_MON_'):]
    assert all(names), 'follower index without a name'

    too_tall = [False] * COUNT
    with open(os.path.join(hg, 'files/fielddata/tsurepoke/tp_param.csv')) as f:
        for row in csv.DictReader(f):
            n = idx['FOLLOWER_MON_' + row['index'][len('TSURE_POKE_'):]]
            too_tall[n] = row['too_tall'] == 'true'

    out = os.path.join(ROOT, 'arm9/asm/gunk_follower')
    os.makedirs(out, exist_ok=True)
    head = '; Generated by tools/gunk/followers/gen_tables.py from pret pokeheartgold. Do not edit.\n'

    def write(name, rows):
        with open(os.path.join(out, name), 'w', newline='\n') as f:
            f.write(head)
            f.writelines(r + '\n' for r in rows)

    write('renderers.inc', [f'\t.word 0x{FIRST_GFX + n:X}, GunkFollower_Renderer ; {names[n]}' for n in range(COUNT)])
    write('details.inc', [f'\t.word 0x{FIRST_GFX + n:X}, 0x{DETAILS:X} ; {names[n]}' for n in range(COUNT)])
    write('textures.inc', [f'\t.word 0x{FIRST_GFX + n:X}, {FIRST_MEMBER + n} ; {names[n]}' for n in range(COUNT)])
    write('model_anims.inc', [
        f'\t.word 0x{FIRST_GFX + n:X}, {MODEL_64 if too_tall[n] else MODEL_32}, {FRAME_SEQ}, GunkFollower_BillboardAnims ; {names[n]}'
        for n in range(COUNT)])

    h = os.path.join(ROOT, 'include/gunk/gunk_follower_species.h')
    with open(h, 'w', newline='\n') as f:
        f.write('// Generated by tools/gunk/followers/gen_tables.py from pret pokeheartgold (src/follow_mon.c). Do not edit.\n')
        f.write('#ifndef POKEDIAMOND_GUNK_FOLLOWER_SPECIES_H\n#define POKEDIAMOND_GUNK_FOLLOWER_SPECIES_H\n\n')
        f.write(f'#define GUNK_FOLLOWER_FIRST_GFX 0x{FIRST_GFX:X}\n#define GUNK_FOLLOWER_COUNT {COUNT}\n\n')
        f.write('// [species]: HG follower index of the species\' first sprite\n')
        f.write(f'static const u16 sGunkFollowerIndex[{SPECIES + 1}] = {{\n')
        for i in range(0, SPECIES + 1, 12):
            f.write('    ' + ', '.join(str(v) for v in model_lut[i:i + 12]) + ',\n')
        f.write('};\n\n// [species - 1]: bit 7 = females use index + 1, bits 0-6 = highest form with its own sprite\n')
        f.write(f'static const u8 sGunkFollowerFlags[{SPECIES}] = {{\n')
        vals = [(0x80 if female[i] else 0) | forms[i] for i in range(SPECIES)]
        for i in range(0, SPECIES, 16):
            f.write('    ' + ', '.join(f'0x{v:02X}' for v in vals[i:i + 16]) + ',\n')
        f.write('};\n\n#endif // POKEDIAMOND_GUNK_FOLLOWER_SPECIES_H\n')
    print(f'wrote {COUNT} rows per table and {SPECIES} species')


if __name__ == '__main__':
    main()
